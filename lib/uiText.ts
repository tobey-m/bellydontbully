export function tr(lang: string, thai: string, english?: string): string {
  const row = words[thai.trim()];
  const index = (['th', 'en', 'zh', 'ja', 'ko'] as CardLang[]).indexOf(lang as CardLang);
  return row?.[Math.max(0, index)] || (lang === 'th' ? thai : english || thai);
}
